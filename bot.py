def parse_max_update(data):
    logger.info(f"Webhook: {json.dumps(data, ensure_ascii=False)[:600]}")
    updates = data if isinstance(data, list) else [data]
    if not updates:
        return None
    item = updates[0]
    ut = item.get("update_type", "")
    if ut == "message_created":
        msg = item.get("message", {})
        return {
            "type": "message",
            "chat_id": msg.get("recipient", {}).get("chat_id"),
            "text": msg.get("body", {}).get("text", ""),
            "user_id": msg.get("sender", {}).get("user_id")
        }
    if ut == "message_callback":
        cb = item.get("callback", {})
        msg = item.get("message", {})
        rec = msg.get("recipient", {}) if msg else {}
        sender = item.get("sender", {})
        chat_id = rec.get("chat_id") or cb.get("chat_id") or sender.get("user_id")
        return {
            "type": "callback",
            "chat_id": chat_id,
            "data": cb.get("payload", ""),
            "user_id": sender.get("user_id") or cb.get("user", {}).get("user_id") or cb.get("from", {}).get("user_id"),
            "callback_id": cb.get("callback_id")
        }
    if ut == "bot_started":
        return {"type": "bot_started", "chat_id": item.get("chat_id"), "user_id": item.get("user_id"), "text": "/start"}
    return None

