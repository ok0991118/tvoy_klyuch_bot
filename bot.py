# ==================== ОТПРАВКА (МИНИМАЛЬНАЯ) ====================
def max_send_text(chat_id, text):
    """Отправка plain text без HTML и без кнопок"""
    url = f"{API_MESSAGES}/messages"
    payload = {
        "chatId": str(chat_id),
        "text": text
    }
    try:
        r = requests.post(url, headers=HEADERS, json=payload, timeout=10, verify=False)
        r.raise_for_status()
        logger.info(f"Отправлено: {r.status_code} | {r.text[:200]}")
        return r.json()
    except Exception as e:
        logger.error(f"Ошибка отправки: {e}")
        return None

def max_send_with_buttons(chat_id, text, buttons):
    """Отправка с кнопками (inline keyboard)"""
    url = f"{API_MESSAGES}/messages"
    payload = {
        "chatId": str(chat_id),
        "text": text,
        "attachments": [{
            "type": "inline_keyboard",
            "payload": {"buttons": buttons}
        }]
    }
    try:
        r = requests.post(url, headers=HEADERS, json=payload, timeout=10, verify=False)
        r.raise_for_status()
        logger.info(f"Отправлено с кнопками: {r.status_code} | {r.text[:200]}")
        return r.json()
    except Exception as e:
        logger.error(f"Ошибка отправки с кнопками: {e}")
        # Fallback: отправляем без кнопок
        max_send_text(chat_id, text + "\n\n(Кнопки не поддерживаются, напиши ответ текстом)")
        return None

# ==================== ПАРСИНГ ====================
def parse_max_update(data):
    logger.info(f"Webhook: {json.dumps(data, ensure_ascii=False)[:600]}")
    update_type = data.get("update_type", "")

    if update_type == "message_created":
        msg = data.get("message", {})
        recipient = msg.get("recipient", {})
        sender = msg.get("sender", {})
        body = msg.get("body", {})
        return {
            "type": "message",
            "chat_id": recipient.get("chat_id"),
            "text": body.get("text", ""),
            "user_id": sender.get("user_id")
        }

    if update_type == "message_callback":
        cb = data.get("callback", {})
        return {
            "type": "callback",
            "chat_id": cb.get("chat_id"),
            "data": cb.get("data", ""),
            "user_id": cb.get("from", {}).get("user_id"),
            "callback_id": cb.get("id")
        }

    if update_type == "bot_started":
        return {
            "type": "bot_started",
            "chat_id": data.get("chat_id"),
            "user_id": data.get("user_id"),
            "text": "/start"
        }

    return None

