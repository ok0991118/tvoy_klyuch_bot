@app.route(WEBHOOK_PATH, methods=["POST"])
def webhook():
    try:
        data = request.get_json(force=True)
        users = load_users()
        update = parse_max_update(data)

        if not update:
            return jsonify({"status": "unknown"}), 200

        cid = update["chat_id"]

        if update["type"] == "callback":
            handle_callback(cid, update["data"], users, update.get("callback_id"), update.get("user_id"))
            return jsonify({"ok": True}), 200

        if update["type"] in ["message", "bot_started"]:
            text = update.get("text", "")
            u = get_user(users, cid)
            user_id = update.get("user_id")

            if text.lower() in ["/start", "дом", "начать", "start", "ключ"]:
                handle_start(cid, users, user_id=user_id)
                return jsonify({"ok": True}), 200

            if u.get("state") == "booked" and text:
                u["custom_slot"] = text
                u["last_activity"] = datetime.now().isoformat()
                save_users(users)
                max_send_text(cid, f"✅ Записала: {text}. Я свяжусь с тобой для уточнения. Жду! 💫", user_id=user_id)
                notify_admin(f"📝 User {cid} написала кастомное время: {text}")
                return jsonify({"ok": True}), 200

            handle_start(cid, users, user_id=user_id)
            return jsonify({"ok": True}), 200

        return jsonify({"ok": True}), 200

    except Exception as e:
        logger.error(f"Webhook error: {e}")
        return jsonify({"error": str(e)}), 500

