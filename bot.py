# ==================== КОНФИГ ====================
MAX_BOT_TOKEN = os.getenv("MAX_BOT_TOKEN", "")
ADMIN_ID = os.getenv("ADMIN_ID", "")  # ID Наташи для уведомлений
WEBHOOK_PATH = "/webhook"
DATA_FILE = "users_state.json"

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s - %(levelname)s - %(message)s"
)
logger = logging.getLogger(__name__)
app = Flask(__name__)

# ==================== ХРАНИЛИЩЕ ====================
def load_users():
    if os.path.exists(DATA_FILE):
        with open(DATA_FILE, "r", encoding="utf-8") as f:
            return json.load(f)
    return {}

def save_users(users):
    with open(DATA_FILE, "w", encoding="utf-8") as f:
        json.dump(users, f, ensure_ascii=False, indent=2)

def get_user(users, uid):
    return users.setdefault(str(uid), {
        "state": "start",
        "answers": {},
        "result_code": "",
        "created_at": datetime.now().isoformat(),
        "last_activity": datetime.now().isoformat(),
        "diagnostic_booked": False,
        "room_choice": ""
    })

# ==================== API MAX ====================
def send_message(chat_id, text, buttons=None):
    url = f"https://api.max.ru/bot{MAX_BOT_TOKEN}/sendMessage"
    payload = {"chat_id": chat_id, "text": text, "parse_mode": "HTML"}
    if buttons:
        payload["reply_markup"] = {"inline_keyboard": buttons}
    try:
        r = requests.post(url, json=payload, timeout=10)
        r.raise_for_status()
        return r.json()
    except Exception as e:
        logger.error(f"Send error: {e}")
        return None

