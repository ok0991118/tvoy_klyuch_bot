def _send_booking_menu(cid, user_id):
    slots = get_planerka_slots()
    slot_buttons = []
    for s in slots:
        slot_buttons.append([{"type": "callback", "text": f"📍 {s['label']}", "payload": f"slot_{s['value']}"}])

    other_buttons = [
        [{"type": "callback", "text": "🎭 Индивидуальная игра", "payload": "book_individual"}],
        [{"type": "callback", "text": "👥 Групповая игра", "payload": "book_group"}]
    ]

    all_buttons = slot_buttons + other_buttons
    max_send_with_buttons(cid, BOOKING_MENU_TEXT, all_buttons, user_id=user_id)

