    st = u.get("state", "start")

    if data == "start_quest" and st == "q1":
        max_send_with_buttons(cid, Q1, Q1_BTNS)
        return

    if st == "q1" and data in "ABC":
        u["answers"]["q1"] = data
        u["state"] = "q2"
        save_users(users)
        max_send_with_buttons(cid, Q2, Q2_BTNS)
        return

    if st == "q2" and data in "ABC":
        u["answers"]["q2"] = data
        u["state"] = "q3"
