def handle_start(cid, users, user_id=None):
    u = get_user(users, cid)
    u["state"] = "intro"
    u["reminder_sent"] = False
    u["last_activity"] = datetime.now().isoformat()
    save_users(users)
    max_send_with_buttons(cid, WELCOME, INTRO_BTN, user_id=user_id)
    notify_admin(f"👤 User {cid} начал диалог (шаг: intro)")

def handle_callback(cid, data, users, callback_id=None, user_id=None):
    if callback_id:
        max_answer_callback(callback_id)

    u = get_user(users, cid)
    u["last_activity"] = datetime.now().isoformat()
    u["reminder_sent"] = False
    st = u.get("state", "start")

    # === НАПОМИНАНИЕ / ПРОДОЛЖЕНИЕ ===
    if data == "reminder_continue":
        if st == "house_choice":
            max_send_with_buttons(cid, HOUSE_TEXT, HOUSE_BTNS, user_id=user_id)
        elif st == "pre_quest":
            max_send_with_buttons(cid, PRE_QUEST_TEXT, PRE_QUEST_BTN, user_id=user_id)
        elif st == "q1":
            max_send_with_buttons(cid, Q1, Q1_BTNS, user_id=user_id)
        elif st == "q2":
            max_send_with_buttons(cid, Q2, Q2_BTNS, user_id=user_id)
        elif st == "q3":
            max_send_with_buttons(cid, Q3, Q3_BTNS, user_id=user_id)
        elif st == "room":
            max_send_with_buttons(cid, ROOM_CHOICE, ROOM_BTNS, user_id=user_id)
        elif st == "booking":
            _send_booking_menu(cid, user_id)
        else:
            handle_start(cid, users, user_id=user_id)
        save_users(users)
        return

    # === ВЫБОР ДОМА ===
    if data == "ready_intro" and st == "intro":
        u["state"] = "house_choice"
        save_users(users)
        max_send_image_by_url(cid, HOUSE_IMAGE_URL, user_id=user_id)
        time.sleep(1)
        max_send_with_buttons(cid, HOUSE_TEXT, HOUSE_BTNS, user_id=user_id)
        notify_admin(f"🏠 User {cid} перешёл к выбору дома")
        return

